                        window.MASTER_CATALOG_SEED.forEach(seedItem => {
                            if (!existingNames.has(seedItem.name.trim().toLowerCase())) {
                                initialCatalog.push(seedItem);
                                addedCount++;
                            }
                        });
                        console.log(`[Seed Migration] Added ${addedCount} new items from seed v${window.APP_DATA_VERSION}.`);
                        safeStorage.setItem('QC_MASTER_CATALOG_DATA', JSON.stringify(initialCatalog));
                        safeStorage.setItem('APP_DATA_VERSION', window.APP_DATA_VERSION);
